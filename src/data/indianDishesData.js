// Helper to get normalized 1-20 strIngredient / strMeasure for backwards compatibility with any component expecting MealDB schema
export const getFullMealData = (dish) => {
  if (!dish) return null;
  const mapped = { ...dish };
  const ingList = Array.isArray(dish.ingredients) ? dish.ingredients : [];
  for (let i = 0; i < 20; i++) {
    if (ingList[i]) {
      mapped[`strIngredient${i + 1}`] = ingList[i].ingredient || "";
      mapped[`strMeasure${i + 1}`] = ingList[i].measure || "";
    } else {
      mapped[`strIngredient${i + 1}`] = "";
      mapped[`strMeasure${i + 1}`] = "";
    }
  }
  mapped.isVeg = dish.dietType === "veg" || dish.isVeg === true;
  return mapped;
};
